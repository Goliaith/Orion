#!/bin/bash
# Write the Arch Linux PKGBUILD (orion-bin) for a release, from its
# SHA256SUMS:
#
#   packaging/pkgbuild.sh VERSION SHA256SUMS > PKGBUILD
#
# It packages the release tarball as is; makepkg -si installs it.
set -euo pipefail
[ $# = 2 ] || { sed -n '2,7p' "$0"; exit 2; }
version=$1 sums=$2
sum() { awk -v f="orion-$1-linux.tar.gz" '$2 == f { print $1 }' "$sums"; }
x86=$(sum x86_64) arm=$(sum aarch64)
top=$(cd "$(dirname "$0")/.." && pwd)
license=$(sed -n 's/^license *= *"\(.*\)"/\1/p' "$top/Cargo.toml" 2>/dev/null || true)
license=${license:-LicenseRef-Proprietary}
[ -n "$x86" ] && [ -n "$arm" ] || { echo "pkgbuild.sh: $sums lacks a tarball" >&2; exit 1; }
cat <<EOF
# Orion, from its release binaries. Generated by packaging/pkgbuild.sh.
pkgname=orion-bin
pkgver=$version
pkgrel=1
pkgdesc='The AI interface layer of an AI-first Linux system, exposed over MCP'
arch=('x86_64' 'aarch64')
url='https://github.com/Goliaith/Orion'
license=('$license')
depends=('glibc')
optdepends=('bubblewrap: the sandbox for tool calls'
            'libnotify: desktop notifications'
            'snapper: snapshots around package changes')
options=('!debug' '!strip')
provides=('orion')
conflicts=('orion')
source_x86_64=("orion-\$pkgver-x86_64-linux.tar.gz::\$url/releases/download/v\$pkgver/orion-x86_64-linux.tar.gz")
source_aarch64=("orion-\$pkgver-aarch64-linux.tar.gz::\$url/releases/download/v\$pkgver/orion-aarch64-linux.tar.gz")
sha256sums_x86_64=('$x86')
sha256sums_aarch64=('$arm')

package() {
    cd "orion-\$CARCH-linux"
    install -Dm755 orion orion-kiosk -t "\$pkgdir/usr/bin/"
    install -Dm644 sysusers.conf "\$pkgdir/usr/lib/sysusers.d/orion.conf"
    for kind in user system; do
        for unit in systemd/\$kind/*; do
            install -dm755 "\$pkgdir/usr/lib/systemd/\$kind"
            sed 's|@BINDIR@|/usr/bin|g' "\$unit" > "\$pkgdir/usr/lib/systemd/\$kind/\${unit##*/}"
        done
    done
    install -Dm644 orion.example.toml docs/* -t "\$pkgdir/usr/share/doc/orion/"
    install -Dm644 LICENSE -t "\$pkgdir/usr/share/licenses/\$pkgname/"
}
EOF
